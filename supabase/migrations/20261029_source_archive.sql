-- Preserve the one-time Google workbook migration alongside normalized app tables.
-- The FORMAT worksheet is intentionally excluded from the migration.

create table if not exists public.income_source_imports (
  id uuid primary key default gen_random_uuid(),
  source_type text not null default 'google_sheets',
  source_file_id text not null,
  source_file_name text not null,
  source_modified_at timestamptz,
  excluded_sheets text[] not null default '{}',
  imported_sheets text[] not null default '{}',
  source_nonempty_rows integer not null default 0,
  reference_rows integer not null default 0,
  qb_transactions integer not null default 0,
  status text not null default 'processing' check (status in ('processing','ready','failed')),
  notes text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.income_source_rows (
  id bigint generated by default as identity primary key,
  import_id uuid references public.income_source_imports(id) on delete cascade,
  source_file_id text not null,
  source_sheet text not null,
  source_row integer not null,
  row_kind text not null default 'raw',
  source_cells jsonb not null,
  source_modified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (source_file_id, source_sheet, source_row)
);

create index if not exists income_source_rows_sheet_row_idx
  on public.income_source_rows(source_sheet, source_row);
create index if not exists income_source_rows_file_idx
  on public.income_source_rows(source_file_id);

alter table public.income_source_imports enable row level security;
alter table public.income_source_rows enable row level security;

-- The archive is internal. The login-free browser app does not need raw-source access.
revoke all on table public.income_source_imports from public, anon, authenticated;
revoke all on table public.income_source_rows from public, anon, authenticated;

alter table public.income_reference_projects
  add column if not exists source_sheet text,
  add column if not exists source_cells jsonb,
  add column if not exists source_file_id text,
  add column if not exists source_modified_at timestamptz;

alter table public.income_qb_transactions
  add column if not exists source_sheet text,
  add column if not exists source_cells jsonb,
  add column if not exists source_file_id text,
  add column if not exists source_modified_at timestamptz;
