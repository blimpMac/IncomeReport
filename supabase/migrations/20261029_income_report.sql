create or replace function public.income_begin_qb_upload(
  p_file_name text,
  p_file_type text,
  p_sheet_name text,
  p_report_date date,
  p_min_date date default null,
  p_max_date date default null
) returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_upload_id uuid;
begin
  select id into v_upload_id
  from public.income_qb_uploads
  where sheet_name = p_sheet_name
  for update;
  if v_upload_id is null then
    insert into public.income_qb_uploads (file_name,file_type,sheet_name,report_date,detected_min_date,detected_max_date,status,transaction_count,uploaded_by)
    values (p_file_name,lower(p_file_type),p_sheet_name,p_report_date,p_min_date,p_max_date,'processing',0,auth.uid())
    returning id into v_upload_id;
  else
    delete from public.income_qb_transactions where upload_id = v_upload_id;
    update public.income_qb_uploads set file_name=p_file_name,file_type=lower(p_file_type),report_date=p_report_date,detected_min_date=p_min_date,detected_max_date=p_max_date,status='processing',error_message=null,transaction_count=0,uploaded_by=auth.uid(),updated_at=now() where id=v_upload_id;
  end if;
  return v_upload_id;
end;
$$;

create or replace function public.income_finalize_qb_upload(p_upload_id uuid,p_transaction_count integer,p_error_message text default null) returns void
language plpgsql security invoker set search_path=public as $$
begin
  update public.income_qb_uploads set status=case when p_error_message is null then 'ready' else 'failed' end,transaction_count=greatest(coalesce(p_transaction_count,0),0),error_message=p_error_message,updated_at=now() where id=p_upload_id;
end;
$$;

revoke all on function public.income_begin_qb_upload(text,text,text,date,date,date) from public, anon;
revoke all on function public.income_finalize_qb_upload(uuid,integer,text) from public, anon;
grant execute on function public.income_begin_qb_upload(text,text,text,date,date,date) to authenticated;
grant execute on function public.income_finalize_qb_upload(uuid,integer,text) to authenticated;

create or replace view public.income_transactions_ready with (security_invoker=true) as
select t.*,u.sheet_name,u.report_date,u.file_name from public.income_qb_transactions t join public.income_qb_uploads u on u.id=t.upload_id where u.status='ready';
revoke all on table public.income_transactions_ready from anon;
grant select on table public.income_transactions_ready to authenticated;

create or replace view public.income_sof_summary with (security_invoker=true) as
with tx as (select * from public.income_transactions_ready), grouped as (
  select coalesce(nullif(sof_key,''),'UNASSIGNED') as sof_key,coalesce(max(nullif(sof_label,'')),'Unassigned') as sof_label,max(nullif(sof_base,'')) as sof_base,count(*)::bigint as transaction_count,min(transaction_date) as first_transaction_date,max(transaction_date) as last_transaction_date,
  round(sum(case when category='Revenue' then credit-debit else 0 end),2) as revenue,
  round(sum(case when category='Materials' then debit-credit else 0 end),2) as materials,
  round(sum(case when category='Labor' then debit-credit else 0 end),2) as labor,
  round(sum(case when category='Overhead' then debit-credit else 0 end),2) as overhead,
  round(sum(case when category='Other' then debit-credit else 0 end),2) as other_cost
  from tx group by coalesce(nullif(sof_key,''),'UNASSIGNED')
)
select g.*,round(g.materials+g.labor+g.overhead+g.other_cost,2) as total_cost,round(g.revenue-(g.materials+g.labor+g.overhead+g.other_cost),2) as gross_profit,
case when g.revenue<>0 then round((g.revenue-(g.materials+g.labor+g.overhead+g.other_cost))/g.revenue*100,2) end as margin_pct,
r.project_name,r.project_status,r.contract_value,r.final_contract_value,r.materials_budget,r.labor_budget,r.overhead_budget,r.total_cost_budget,
case when r.total_cost_budget is not null and r.total_cost_budget<>0 then round(r.total_cost_budget-(g.materials+g.labor+g.overhead+g.other_cost),2) end as budget_variance
from grouped g left join lateral (
  select rr.* from public.income_reference_projects rr where rr.sof_key=g.sof_key or (rr.sof_base is not null and rr.sof_base=g.sof_base)
  order by (rr.sof_key=g.sof_key) desc,rr.source_row asc limit 1
) r on true;
revoke all on table public.income_sof_summary from anon;
grant select on table public.income_sof_summary to authenticated;

create or replace function public.income_monthly_report(p_month date) returns jsonb
language sql stable security invoker set search_path=public as $$
with bounds as (select date_trunc('month',p_month)::date start_date,(date_trunc('month',p_month)+interval '1 month')::date end_date),
tx as (select t.* from public.income_transactions_ready t,bounds b where t.transaction_date>=b.start_date and t.transaction_date<b.end_date),
agg as (
 select count(*)::bigint transaction_count,count(distinct nullif(sof_key,''))::bigint unique_sof,count(*) filter(where sof_key is null or sof_key='')::bigint unassigned_count,
 round(coalesce(sum(case when category='Revenue' then credit-debit else 0 end),0),2) revenue,
 round(coalesce(sum(case when category='Materials' then debit-credit else 0 end),0),2) materials,
 round(coalesce(sum(case when category='Labor' then debit-credit else 0 end),0),2) labor,
 round(coalesce(sum(case when category='Overhead' then debit-credit else 0 end),0),2) overhead,
 round(coalesce(sum(case when category='Other' then debit-credit else 0 end),0),2) other_cost from tx),
accounts as (select coalesce(account,'Unspecified') account,round(sum(debit-credit),2) net_cost from tx where category<>'Revenue' group by coalesce(account,'Unspecified') order by abs(sum(debit-credit)) desc limit 5)
select jsonb_build_object('month',to_char(p_month,'YYYY-MM'),'transaction_count',a.transaction_count,'unique_sof',a.unique_sof,'unassigned_count',a.unassigned_count,'revenue',a.revenue,'materials',a.materials,'labor',a.labor,'overhead',a.overhead,'other_cost',a.other_cost,'total_cost',round(a.materials+a.labor+a.overhead+a.other_cost,2),'gross_profit',round(a.revenue-(a.materials+a.labor+a.overhead+a.other_cost),2),'margin_pct',case when a.revenue<>0 then round((a.revenue-(a.materials+a.labor+a.overhead+a.other_cost))/a.revenue*100,2) end,'top_cost_accounts',coalesce((select jsonb_agg(jsonb_build_object('account',account,'net_cost',net_cost)) from accounts),'[]'::jsonb)) from agg a;
$$;

create or replace function public.income_monthly_sof_summary(p_month date)
returns table(sof_key text,sof_label text,transaction_count bigint,revenue numeric,materials numeric,labor numeric,overhead numeric,other_cost numeric,total_cost numeric,gross_profit numeric,margin_pct numeric)
language sql stable security invoker set search_path=public as $$
with bounds as (select date_trunc('month',p_month)::date start_date,(date_trunc('month',p_month)+interval '1 month')::date end_date),g as (
 select coalesce(nullif(t.sof_key,''),'UNASSIGNED') sof_key,coalesce(max(nullif(t.sof_label,'')),'Unassigned') sof_label,count(*)::bigint transaction_count,
 round(sum(case when t.category='Revenue' then t.credit-t.debit else 0 end),2) revenue,
 round(sum(case when t.category='Materials' then t.debit-t.credit else 0 end),2) materials,
 round(sum(case when t.category='Labor' then t.debit-t.credit else 0 end),2) labor,
 round(sum(case when t.category='Overhead' then t.debit-t.credit else 0 end),2) overhead,
 round(sum(case when t.category='Other' then t.debit-t.credit else 0 end),2) other_cost
 from public.income_transactions_ready t,bounds b where t.transaction_date>=b.start_date and t.transaction_date<b.end_date group by coalesce(nullif(t.sof_key,''),'UNASSIGNED'))
select g.sof_key,g.sof_label,g.transaction_count,g.revenue,g.materials,g.labor,g.overhead,g.other_cost,round(g.materials+g.labor+g.overhead+g.other_cost,2),round(g.revenue-(g.materials+g.labor+g.overhead+g.other_cost),2),case when g.revenue<>0 then round((g.revenue-(g.materials+g.labor+g.overhead+g.other_cost))/g.revenue*100,2) end from g order by abs(g.revenue)+abs(g.materials+g.labor+g.overhead+g.other_cost) desc;
$$;

revoke all on function public.income_monthly_report(date) from public, anon;
revoke all on function public.income_monthly_sof_summary(date) from public, anon;
grant execute on function public.income_monthly_report(date) to authenticated;
grant execute on function public.income_monthly_sof_summary(date) to authenticated;
