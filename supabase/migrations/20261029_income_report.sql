-- E-WORKS Income Report isolated schema objects.
-- Reuses the existing Supabase project but never touches the existing RFP tables.

create extension if not exists pgcrypto;

create table if not exists public.income_reference_projects (
  id bigint generated by default as identity primary key,
  source_row integer not null unique,
  project_name text,
  sof_number text,
  sof_key text,
  sof_base text,
  po_contract text,
  project_location text,
  client_name text,
  project_owner text,
  construction_classification text,
  scope_of_works text,
  pic text,
  contact_no text,
  date_of_award date,
  start_date date,
  target_completion_date date,
  contract_value numeric(18,2),
  planned_pct numeric(12,6),
  actual_pct numeric(12,6),
  remarks text,
  project_status text,
  actual_completion_date date,
  final_contract_value numeric(18,2),
  certificate_of_completion text,
  project_code text,
  cancelled_date date,
  materials_budget numeric(18,2) not null default 0,
  labor_budget numeric(18,2) not null default 0,
  overhead_budget numeric(18,2) not null default 0,
  tpc_budget numeric(18,2) not null default 0,
  total_cost_budget numeric(18,2) not null default 0,
  source_updated_at timestamptz not null default now()
);

create index if not exists income_reference_sof_key_idx on public.income_reference_projects (sof_key);
create index if not exists income_reference_sof_base_idx on public.income_reference_projects (sof_base);
create index if not exists income_reference_status_idx on public.income_reference_projects (project_status);

create table if not exists public.income_qb_uploads (
  id uuid primary key default gen_random_uuid(),
  file_name text not null,
  file_type text not null check (file_type in ('csv','xlsx','xls')),
  sheet_name text not null unique,
  report_date date not null,
  detected_min_date date,
  detected_max_date date,
  transaction_count integer not null default 0,
  status text not null default 'processing' check (status in ('processing','ready','failed')),
  error_message text,
  uploaded_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists income_qb_upload_report_date_idx on public.income_qb_uploads (report_date desc);
create index if not exists income_qb_upload_status_idx on public.income_qb_uploads (status);

create table if not exists public.income_qb_transactions (
  id bigint generated by default as identity primary key,
  upload_id uuid not null references public.income_qb_uploads(id) on delete cascade,
  source_row integer not null,
  division text,
  project_group text,
  sof_label text,
  sof_key text,
  sof_base text,
  type text,
  transaction_date date,
  num text,
  name text,
  memo text,
  account text,
  debit numeric(18,2) not null default 0,
  credit numeric(18,2) not null default 0,
  balance numeric(18,2),
  category text not null default 'Other' check (category in ('Revenue','Materials','Labor','Overhead','Other')),
  created_at timestamptz not null default now(),
  unique (upload_id, source_row)
);

create index if not exists income_qb_tx_date_idx on public.income_qb_transactions (transaction_date desc);
create index if not exists income_qb_tx_sof_idx on public.income_qb_transactions (sof_key);
create index if not exists income_qb_tx_sof_base_idx on public.income_qb_transactions (sof_base);
create index if not exists income_qb_tx_category_idx on public.income_qb_transactions (category);
create index if not exists income_qb_tx_upload_idx on public.income_qb_transactions (upload_id);

alter table public.income_reference_projects enable row level security;
alter table public.income_qb_uploads enable row level security;
alter table public.income_qb_transactions enable row level security;

drop policy if exists "income_reference_authenticated_read" on public.income_reference_projects;
